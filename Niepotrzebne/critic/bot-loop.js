(async () => {
  const w = (ms) => new Promise((r) => setTimeout(r, ms));
  const log = { ev: [] }; RR.report = () => log;
  const ev = (s) => log.ev.push(`${(performance.now() / 1000).toFixed(1)} ${s}`);
  const tin = RR.trucks.find((t) => t.role === 'in'), tout = RR.trucks.find((t) => t.role === 'out');
  while (tin.state !== 'open') await w(200);
  ev(`inbound open, rugs inside ${tin.carpetsInside().length}`);
  const roll = tin.carpetsInside()[0];
  roll.body.setTranslation({ x: 2, y: 0.5, z: -3 }, true);
  RR.physics.teleportBinding(roll.body);
  await w(1500);
  ev(`roll moved state=${roll.state}`);
  roll.unroll(new RR.engine.camera.position.constructor(1, 0, 0));
  await w(2500);
  ev(`after unroll state=${roll.state} rf=${roll.rolledFraction?.toFixed?.(2)}`);
  const flat = RR.debug.rugFlat('cut', 'M', 9, 6 - 2.3, 0, true);
  await w(1200);
  ev(`belt rug state=${flat.state} onBelt=${RR.roller.onBelt(flat)}`);
  RR.roller.press();
  ev(`roller ${RR.roller.state} msg=${RR.roller.message}`);
  const t0 = performance.now();
  while (RR.roller.state !== 'cooldown' && performance.now() - t0 < 25000) await w(250);
  ev(`roller done state=${RR.roller.state} wrapped=${flat.wrapped} rugState=${flat.state} price=${flat.finalPrice} grade=${flat.finalEval?.grade}`);
  while (tout.state !== 'open') await w(250);
  const slot = tout.cargoSlot(0);
  flat.body.setTranslation({ x: slot.x, y: slot.y + 0.3, z: slot.z }, true);
  RR.physics.teleportBinding(flat.body);
  await w(1500);
  ev(`in outbound: ${tout.carpetsInside().length} wrapped=${tout.carpetsInside().filter((c) => c.wrapped).length}`);
  const m0 = RR.economy.money;
  tout.dispatchRequested = true;
  while (tout.state !== 'leave' && tout.state !== 'away') await w(250);
  await w(500);
  ev(`dispatched money ${m0} -> ${RR.economy.money}, truck ${tout.state}`);
  log.done = true;
})();
1
