import { open, sleep, guard } from './h.mjs';
guard(120000);
const host = await open('host', { query: '', w: 1280, h: 720 });
await host.ev(() => window.RR.startHost('Pour check 2'));
const roomId = await host.ev(() => RR.net.roomId);
await host.ev(() => { RR.shift.t = 120; RR.debug.rugFlat('cut', 'M', 0, -3.5, 0, true); });
await sleep(1000);
const cl = await open('client', { query: '', w: 1280, h: 720 });
await cl.ev((id) => window.RR.joinRoom(id), roomId);
await sleep(5000);
await cl.ev(() => { RR.debug.teleport(0, -1.1, 0, -0.9); }); await sleep(800);
const diag = () => cl.ev(() => ({ blocked: !!RR.grab.blocked?.(), ragdolled: RR.player.ragdolled, proxy: !!RR.grab.proxy, label: RR.hud.labelOpen, shop: RR.shop.isOpen, veh: !!RR.player.inVehicle, eCons: RR.eConsumed, locked: RR.input.locked, frozen: RR.player.frozen, aimOwner: RR.grab.aim?.owner?.kind ?? null, held: RR.grab.held?.kind ?? null, carpets: RR.carpets.list.length, mode: RR.mode }));
console.log('diag before hold', JSON.stringify(await diag()));
await cl.ev(() => { RR.debug.hold('lathera'); }); await sleep(600);
await cl.ev(() => { RR.debug.look(0, 0.05, -3.5); }); await sleep(300);
console.log('diag after look', JSON.stringify(await diag()));
await cl.ev(() => RR.debug.lmb(true)); await sleep(2500);
console.log('diag while pouring', JSON.stringify(await diag()), 'held fill', await cl.ev(() => RR.grab.held?.item?.fill ?? null), 'tilt', await cl.ev(() => RR.grab.held?.item?.tilt ?? null));
await cl.ev(() => RR.debug.lmb(false));
host.flush(); cl.flush(); await host.close(); await cl.close(); console.log('done');
