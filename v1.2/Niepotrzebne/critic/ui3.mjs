const pg = p.page;
await sleep(600);
await p.shot('ui/01-title-first-visit.png');
await pg.getByRole('button', { name: /settings/i }).click(); await sleep(500); await p.shot('ui/01b-settings.png');
await pg.getByRole('button', { name: /^done$/i }).click(); await sleep(400);
await pg.locator('button.rr-btn.pink.small').first().click(); await sleep(700); await p.shot('ui/02-creator.png');
await pg.getByRole('button', { name: /^done$/i }).click(); await sleep(400);
await pg.getByRole('button', { name: /play solo/i }).click(); await sleep(1500);
