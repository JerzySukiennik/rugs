(async () => {
  const w = (ms) => new Promise((r) => setTimeout(r, ms));
  const log = { notes: [] }; RR.report = () => log;
  const c = RR.debug.rugFlat('cut', 'M', 0, -3.5, 0, true); await w(700);
  const st = RR.chem.state(c);
  const uv = { u: 0.5, v: 0.5 }, R = 0.25;
  const disc = (fn) => { let s = 0, n = 0; st.surface.forEachInRadius(uv.u, uv.v, R, (x, y) => { s += fn(y * st.W + x); n++; }); return n ? +(s / n).toFixed(4) : 0; };
  st.surface.forEachInRadius(uv.u, uv.v, R, (x, y, wgt) => { const i = y * st.W + x; st.f.surf[i] = 1.0 * wgt + 0.2; st.f.gel[i] = 0.4 * wgt; st.f.powder[i] = 0.3 * wgt; st.active[i] = 1; RR.chem.syncCell(st, i); });
  const snap = (tag) => ({ tag, surf: disc((i) => st.f.surf[i]), gel: disc((i) => st.f.gel[i]), powder: disc((i) => st.f.powder[i]), water: disc((i) => st.f.water[i]) });
  log.notes.push(snap('before'));
  const counts = { chemDeposit: {}, fluidsDeposit: {}, liters: 0 };
  const od = RR.chem.deposit.bind(RR.chem);
  RR.chem.deposit = (carpet, uvv, kind, pid, amount, rad) => { counts.chemDeposit[kind] = (counts.chemDeposit[kind] ?? 0) + 1; counts.liters += amount || 0; return od(carpet, uvv, kind, pid, amount, rad); };
  const ofd = RR.fluids.onDeposit;
  RR.fluids.onDeposit = (h) => { counts.fluidsDeposit[h.kind] = (counts.fluidsDeposit[h.kind] ?? 0) + 1; return ofd(h); };
  const pt = c.uvToWorld(uv.u, uv.v).point;
  RR.debug.teleport(pt.x + 0.1, pt.z + 0.85, 0, -0.9); await w(300);
  RR.debug.holdHose(); await w(400);
  RR.debug.look(pt.x, pt.y, pt.z); await w(150);
  RR.debug.lmb(true);
  await w(4000);
  RR.debug.lmb(false); await w(400);
  log.notes.push(snap('after 4s hose on center'));
  log.counts = counts;
  log.hoseReport = RR.hose?.flowing ?? null;
  log.fl = RR.fluids.report?.().totalLiters;
  log.done = true;
})();
