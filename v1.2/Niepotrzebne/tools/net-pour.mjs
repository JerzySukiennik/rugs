// Rug Rush co-op pour test with real DOM keyboard/mouse events on the client.
import { launch, flush, sleep, shot, guard, closeAll } from './netkit.mjs';

guard(200000);
const host = await launch('host', { query: '' });
await host.ev(() => window.RR.startHost('Pour test'));
const roomId = await host.ev(() => window.RR.net.roomId);
await host.ev(() => { window.__rug = window.RR.debug.rugFlat('cut', 'M', 0, 4, 0, true); });
const cl = await launch('c1', { query: '', w: 1000, h: 600 });
await cl.ev((id) => window.RR.joinRoom(id), roomId);
await sleep(3000);
const bottle = await cl.ev(() => { const it = window.RR.items.find((i) => i.productId === 'lathera'); const t = it.body.translation(); return { x: t.x, y: t.y, z: t.z, id: it.id }; });
console.log('[T] bottle', JSON.stringify(bottle));
await cl.ev((b) => { const R = window.RR; R.input.locked = true; R.input.autoLock = false; R.debug.teleport(b.x + 1.1, b.z, Math.PI / 2, 0); }, bottle);
await sleep(500);
await cl.ev((b) => window.RR.debug.look(b.x, b.y + 0.08, b.z), bottle);
await sleep(400);
const aim = await cl.ev(() => window.RR.grab.aim?.owner?.label ?? null);
console.log('[T] client aims at', aim);
await cl.page.keyboard.down('KeyE');
await sleep(80);
await cl.page.keyboard.up('KeyE');
await sleep(800);
const held = await cl.ev(() => window.RR.grab.heldItem?.()?.label ?? window.RR.grab.held?.kind ?? null);
console.log('[T] client holds', held);
await cl.ev(() => { const R = window.RR; R.debug.teleport(0.2, 5.4, 0, -0.9); });
await sleep(600);
await cl.ev(() => window.RR.debug.look(0, 0, 4));
await sleep(300);
await cl.page.mouse.move(500, 300);
await cl.page.mouse.down();
await sleep(3500);
await cl.page.mouse.up();
await sleep(1500);
const res = await host.ev(() => { const st = window.RR.chem.state(window.__rug); const avg = (k) => +(st.f[k].reduce((a, b) => a + b, 0) / st.N).toFixed(4); const it = window.RR.items.find((i) => i.productId === 'lathera'); return { gel: avg('gel'), surf: avg('surf'), fill: +it.fill.toFixed(3) }; });
console.log('[T] host rug after client pour', JSON.stringify(res));
await shot(cl, 'pour-client.png');
flush(host);
flush(cl);
await closeAll();
